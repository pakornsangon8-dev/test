def get_gender_from_title(title):
    if pd.isna(title): return 'ไม่ระบุ'
    title = str(title).strip()
    if 'หญิง' in title or title in ['นาง', 'นางสาว']:
        return 'หญิง'
    elif title == 'นาย' or any(rank in title for rank in ['พล', 'พัน', 'ร้อย', 'ว่าที่', 'จ่า', 'สิบ', 'นาวา', 'ดาบตำรวจ']):
        return 'ชาย'
    return 'ไม่ระบุ'

def load_lookup_from_excel(file_path: str, agency_col: str = "agency", province_col: str = "province") -> dict:
    try:
        df_lookup = pd.read_excel(file_path)
        lookup_dict = dict(zip(df_lookup[agency_col].astype(str).str.strip(), df_lookup[province_col].astype(str).str.strip()))
        return lookup_dict
    except Exception as e:
        print(f"Warning: Failed to load external Excel lookup: {e}")
        return {}

def process_raw_dataframe(df_raw, source_filename="unknown", upload_time=None, lookup_excel_path=None):
    df = df_raw.copy()
    # 3. หาจังหวัดจากหน่วยงาน
    if 'จังหวัด' not in df.columns and 'หน่วยงาน' in df.columns:
        
        # --- เพิ่มโค้ดล้างอักขระขยะและช่องว่างพิเศษตรงนี้ ---
        df['หน่วยงาน'] = df['หน่วยงาน'].astype(str).str.replace('\xa0', ' ', regex=False).str.replace('\u200b', '', regex=False).str.strip()
        # ---------------------------------------------
        
        df['จังหวัด'] = df['หน่วยงาน'].apply(lambda x: agency_map.get(str(x).strip(), 'รอตรวจสอบ'))
        
    agency_map = AGENCY_TO_PROVINCE.copy()
    if lookup_excel_path and os.path.exists(lookup_excel_path):
        external_lookup = load_lookup_from_excel(lookup_excel_path)
        agency_map.update(external_lookup)
    
    rename_mapping = {}
    for col in df.columns:
        if '(' in col and ')' in col:
            clean_col = col.split('(')[0].strip()
            rename_mapping[col] = clean_col
            
    if rename_mapping:
        df.rename(columns=rename_mapping, inplace=True)
    
    target_id_col = None
    for cand in ['P_ID', 'p_id', 'รายที่', 'ลำดับที่']:
        if cand in df.columns:
            target_id_col = cand
            break
            
    if target_id_col:
        df['check_numeric'] = pd.to_numeric(df[target_id_col], errors='coerce')
        df = df[df['check_numeric'].notna()]
        df = df.drop(columns=['check_numeric'])
        
    if 'ชื่อ' in df.columns:
        df = df[df['ชื่อ'].notna()] 
        df = df[df['ชื่อ'].astype(str).str.strip() != ''] 
        df = df[df['ชื่อ'].astype(str).str.strip().str.lower() != 'nan']

    if 'คำนำหน้าชื่อ' in df.columns:
        df = df[~df['คำนำหน้าชื่อ'].astype(str).str.contains('รวม|สรุป|total|Total', regex=True, na=False)]
        
    if 'ลำดับ' in df.columns:
        df = df[~df['ลำดับ'].astype(str).str.contains('รวม|สรุป|total|Total', regex=True, na=False)]
    
    if 'อีเมล' not in df.columns:
        df['อีเมล'] = 'ไม่ระบุ'
    else:
        df['อีเมล'] = df['อีเมล'].fillna('ไม่ระบุ')
        df['อีเมล'] = df['อีเมล'].replace(r'^\s*$', 'ไม่ระบุ', regex=True)
        df['อีเมล'] = df['อีเมล'].replace('None', 'ไม่ระบุ')

    if 'ชื่อ' in df.columns and 'นามสกุล' in df.columns:
        prefix_series = df['คำนำหน้าชื่อ'].fillna('').astype(str).str.strip() if 'คำนำหน้าชื่อ' in df.columns else ''
        df['ชื่อ-นามสกุล'] = prefix_series + df['ชื่อ'].fillna('').astype(str).str.strip() + " " + df['นามสกุล'].fillna('').astype(str).str.strip()
        df['clean_full_name'] = df['ชื่อ'].fillna('').astype(str).str.strip() + " " + df['นามสกุล'].fillna('').astype(str).str.strip()
    
    if 'เพศ' not in df.columns and 'คำนำหน้าชื่อ' in df.columns:
        df['เพศ'] = df['คำนำหน้าชื่อ'].apply(get_gender_from_title)
        
    if 'จังหวัด' not in df.columns and 'หน่วยงาน' in df.columns:
        df['จังหวัด'] = df['หน่วยงาน'].apply(lambda x: agency_map.get(str(x).strip(), 'รอตรวจสอบ'))
        
    if 'ภาค' not in df.columns:
        df['ภาค'] = df['จังหวัด'].apply(lambda x: PROVINCE_TO_REGION.get(str(x).strip(), 'รอตรวจสอบ'))

    announcements_db = get_announcement_dict()
    
    def get_start_date(ann_no):
        try:
            return announcements_db.get(int(ann_no), {}).get('start_date', None)
        except:
            return None
            
    def get_minister(ann_no):
        try:
            return announcements_db.get(int(ann_no), {}).get('minister_name', None)
        except:
            return None

    if 'ประกาศฉบับที่' in df.columns:
        df['วันที่เริ่ม (announcement_date)'] = df['ประกาศฉบับที่'].apply(get_start_date)
        df['รัฐมนตรี (minister)'] = df['ประกาศฉบับที่'].apply(get_minister)
        
    today = datetime.today()
    
    expiry_dates = []
    remaining_days_list = []
    
    for i, row in df.iterrows():
        date_str = row.get('วันที่เริ่ม (announcement_date)')
        ann_no = row.get('ประกาศฉบับที่')
            
        if pd.isna(date_str) or date_str is None:
            expiry_dates.append(None)
            remaining_days_list.append(None)
            continue
        try:
            date_str_clean = str(date_str).replace('\\', '/')
            
            import re
            match = re.search(r'(\d{1,2})[/.-](\d{1,2})[/.-](\d{4})', date_str_clean)
            if match:
                d = int(match.group(1))
                m = int(match.group(2))
                y = int(match.group(3))
                
                if y > 2400:
                    y -= 543
                    
                start_date_obj = datetime(year=y, month=m, day=d)
            else:
                start_date_obj = datetime.strptime(date_str_clean, "%d/%m/%Y")
                if start_date_obj.year > 2400:
                    start_date_obj = start_date_obj.replace(year=start_date_obj.year - 543)

            try:
                term_yrs = announcements_db.get(int(ann_no), {}).get('term_years', 4.0) or 4.0
            except:
                term_yrs = 4.0
                
            expiry_date_obj = start_date_obj + relativedelta(years=int(term_yrs)) - timedelta(days=1)
                
            thai_year = expiry_date_obj.year + 543
            expiry_dates.append(f"{expiry_date_obj.day:02d}/{expiry_date_obj.month:02d}/{thai_year}")
            
            delta = expiry_date_obj - today
            remaining_days_list.append(delta.days)
        except Exception as e:
            expiry_dates.append(None)
            remaining_days_list.append(None)
            
    df['วันหมดอายุบัตร'] = expiry_dates
    df['ระยะวันที่หมดอายุไปแล้วหรือเหลืออีกกี่วันจะหมดอายุ'] = remaining_days_list  
    
    if 'ประกาศฉบับที่' in df.columns:
        df['ลำดับตามประกาศ'] = df.groupby('ประกาศฉบับที่').cumcount() + 1
        
    df = df.reset_index(drop=True)
    df['ลำดับรวม'] = df.index + 1
        
    def get_status_type(days):
        if pd.isna(days): return 'UNKNOWN'
        if days < 0: return 'EXPIRED'
        elif days <= 90: return 'WARNING'
        else: return 'ACTIVE'
        
    df['status_type'] = df['ระยะวันที่หมดอายุไปแล้วหรือเหลืออีกกี่วันจะหมดอายุ'].apply(get_status_type)

    if 'clean_full_name' in df.columns:
        name_counts = df['clean_full_name'].value_counts()
        df['is_duplicate'] = df['clean_full_name'].map(lambda x: name_counts.get(x, 0) > 1)
    
    current_time_str = upload_time or datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    df['source_file'] = source_filename
    df['upload_time'] = current_time_str
        
    # ตัดคอลัมน์ "เทียบเท่า 8" และ "ไม่เทียบเท่า 8" ออกจากลิสต์ เพื่อไม่ให้บันทึกลง DB
    cols_order = [
        'source_file', 'upload_time',
        'ประกาศฉบับที่', 'ลำดับตามประกาศ', 'คำนำหน้าชื่อ', 'ชื่อ', 'นามสกุล', 'ชื่อ-นามสกุล',
        'เพศ', 'หน่วยงาน', 'จังหวัด', 'ภาค',
        'วันที่เริ่ม (announcement_date)', 'วันหมดอายุบัตร',
        'ระยะวันที่หมดอายุไปแล้วหรือเหลืออีกกี่วันจะหมดอายุ', 'status_type', 'is_duplicate',
        'รัฐมนตรี (minister)', 'หมายเหตุ', 'อีเมล'
    ]
    
    final_cols = [c for c in cols_order if c in df.columns]
    
    # กรองตัดคอลัมน์ขยะหรือคอลัมน์ที่ไม่ต้องการทิ้ง
    exclude_cols = ['บัตรหมดอายุ', 'เทียบเท่า 8', 'ไม่เทียบเท่า 8', 'เทียบเท่า', 'ไม่เทียบเท่า']
    other_cols = [c for c in df.columns if c not in final_cols and c not in exclude_cols]
    
    return df[final_cols + other_cols]